#! /usr/bin/env perl

use v5.38;
use Unicode::UCD 'prop_invlist';

# prop_invlist returns an array whos odd indices start the include section, and the even
# ones represent the stop. we invert these list so they represent NOT having the quality
my @non_words    = (0, prop_invlist('Word'),         0x10FFFF);
my @non_start    = (0, prop_invlist('XID_Start'),    0x10FFFF);
my @non_continue = (0, prop_invlist('XID_Continue'), 0x10FFFF);

use List::Util qw/pairmap/;

# Core modules only, so the generator runs on a bare perl.
sub spew ($file, $content) {
  open my $fh, '>:encoding(UTF-8)', $file or die "$file: $!";
  print $fh $content;
  close $fh or die "$file: $!";
}

# Inclusive [start, end] ranges; ones that overlap or touch become one.
sub merge ($ranges) {
  my @merged;
  for my $range (sort { $a->[0] <=> $b->[0] or $a->[1] <=> $b->[1] } $ranges->@*) {
    if (@merged and $range->[0] <= $merged[-1][1] + 1) {
      $merged[-1][1] = $range->[1] if $range->[1] > $merged[-1][1];
    } else {
      push @merged, [ $range->@* ];
    }
  }
  return \@merged;
}

# we merge the ranges here, so we see all codepoints that don't have the prop
sub merge_with_non_words (@interested_range) {
  my $merged = merge([ pairmap { [ $a => $b ] } @non_words, @interested_range ]);
  # and now we flip it back!
  shift $merged->[0]->@*;
  pop $merged->[-1]->@*;
  my @final = map $_->@*, $merged->@*;
  return @final;
}

sub render_array (@range_pairs) {
  my $rendered = join "\n", '{', join(",\n", pairmap {"  { $a, $b }"} @range_pairs), '}';
}

# ASCII is nearly every codepoint the scanner asks about, and the binary search
# costs a dozen indirect calls per lookup. Membership for 0..127 comes from two
# words computed out of the same ranges, so the two can't disagree.
sub render_ascii_bitmap (@range_pairs) {
  my @words = (0, 0);
  pairmap {
    $words[ $_ >> 6 ] |= 1 << ($_ & 63) for grep { $_ < 128 } $a .. ($b > 128 ? 128 : $b) - 1;
  } @range_pairs;
  return sprintf '{ 0x%016xULL, 0x%016xULL }', @words;
}
sub render_predicate ($name, @range_pairs) {
  return <<C;
static const struct TSPRange tsp_$name\[] = ${\render_array @range_pairs};
static const uint64_t tsp_${name}_ascii[2] = ${\render_ascii_bitmap @range_pairs};

static bool is_tsp_$name (int32_t codepoint) {
  if ((uint32_t)codepoint < 128) return (tsp_${name}_ascii[codepoint >> 6] >> (codepoint & 63)) & 1;
  return tsp_bsearch(&codepoint, tsp_$name, sizeof(tsp_$name) / sizeof(tsp_$name\[0]), sizeof(tsp_$name\[0]), tsprange_contains);
}
C
}
my @idstart    = merge_with_non_words(@non_start);
my @idcont     = merge_with_non_words(@non_continue);
my @whitespace = prop_invlist 'White_Space';

spew('./src/tsp_unicode.h', <<C);
/* THIS FILE IS GENERATED BY unicode_ranges.pl */

#ifndef TSP_UNICODE_H
#define TSP_UNICODE_H

#include "bsearch.h"
#include <stdint.h>
#include <stdbool.h>

struct TSPRange { int32_t start; int32_t end; };
static int tsprange_contains (const void * a, const void * b) {
  struct TSPRange * range = (struct TSPRange*)b;
  int32_t key = *(int32_t*)a;
  if (key < range->start)
    return -1;
  if (key >= range->end)
    return 1;
  return 0;
}

${\render_predicate id_start => @idstart}
${\render_predicate id_continue => @idcont}
${\render_predicate whitespace => @whitespace}
#endif /* TSP_UNICODE_H */
C

# now we build the JS regexes
spew('./lib/unicode_ranges.js', <<JS);
// NOTE - this is generated by unicode_ranges.pl
module.exports = {
  // these patterns are simply XID_Start followed by XID_Continue, minus things which don't match perl's \\p{Word}
  identifier: /[_\\p{XID_Start}][\\p{XID_Continue}]*/v,
  // Any amount of :: before/between/after identifiers. NOTE the anchored shape:
  // the repeat re-enters only on the `::` literal, never directly back into the
  // huge XID class. The "obvious" form ((::)|IDENT)+ loops the repeat over an
  // alternation containing XID_Continue, which makes clang's wasm codegen blow
  // up to >16GB and OOM the release runner (same family as tree-sitter#3496).
  // Keep this anchored; do not "simplify" it back to (A|B)+.
  bareword:   /(::)*[_\\p{XID_Start}][\\p{XID_Continue}]*((::)+[_\\p{XID_Start}][\\p{XID_Continue}]*)*(::)*|(::)+/v,
}
JS
